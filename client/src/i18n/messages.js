// All interface text in Arabic (default) and English.
// Keys with a count have plural forms: Arabic uses zero/one/two/few/many/other, English one/other.

/** Expands { key: { one, other, ... } } into 'key.one', 'key.other', ... */
function plurals(map) {
  const out = {};
  for (const [key, forms] of Object.entries(map)) {
    for (const [form, text] of Object.entries(forms)) out[`${key}.${form}`] = text;
  }
  return out;
}

